function Para([string]$text, [int]$halfPoints = 20, [string]$color = '', [bool]$bold = $false, [string]$align = 'right', [bool]$center = $false) {
  $jc = if ($center -or $align -eq 'center') { 'center' } else { 'right' }
  $b = if ($bold) { '<w:b/><w:bCs/>' } else { '' }
  $c = if ($color) { "<w:color w:val=`"$color`"/>" } else { '' }
  AppendXml @"
<w:p>
  <w:pPr><w:bidi/><w:jc w:val="$jc"/></w:pPr>
  <w:r><w:rPr><w:rFonts w:ascii="Arial" w:hAnsi="Arial" w:cs="Arial"/>$b$c<w:sz w:val="$halfPoints"/><w:szCs w:val="$halfPoints"/><w:rtl/></w:rPr><w:t xml:space="preserve">$(XmlEsc $text)</w:t></w:r>
</w:p>
"@
}

